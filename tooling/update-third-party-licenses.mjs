import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = join(root, "docs/third-party-licenses");
const check = process.argv.includes("--check");
const graphOption = process.argv.indexOf("--graph");
const graphFile = graphOption === -1 ? undefined : process.argv[graphOption + 1];
if (graphOption !== -1 && !graphFile) throw new Error("--graph requires a pnpm list JSON file.");
const graph = JSON.parse(
  graphFile
    ? readFileSync(graphFile, "utf8")
    : execFileSync("pnpm", ["list", "-r", "--prod", "--depth", "Infinity", "--json"], {
        cwd: root,
        encoding: "utf8",
        maxBuffer: 16 * 1024 * 1024,
      }),
);
const packages = new Map();
function add(directory, scope) {
  const pkg = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
  if (pkg.private || pkg.name.startsWith("@open-3d/")) return;
  packages.set(`${pkg.name}@${pkg.version}`, { pkg, directory, scope });
}
function walk(dependencies, parentDirectory) {
  const optional = parentDirectory
    ? JSON.parse(readFileSync(join(parentDirectory, "package.json"), "utf8")).optionalDependencies
    : undefined;
  for (const [name, dependency] of Object.entries(dependencies ?? {})) {
    // pnpm lists platform-specific optional packages even when they are not installed.
    // Missing required packages must still fail rather than silently dropping a notice.
    if (dependency.path && !existsSync(join(dependency.path, "package.json")) && optional?.[name]) continue;
    if (dependency.path) add(dependency.path, "Production dependency graph");
    walk(dependency.dependencies, dependency.path);
  }
}
for (const workspace of graph) walk(workspace.dependencies);
// These build-time packages also supply distributed styles and UI source.
for (const name of ["shadcn", "tailwindcss"]) {
  add(realpathSync(join(root, "apps/web/node_modules", name)), "Styles / adapted UI source");
}
add(realpathSync(join(root, "node_modules/vite")), "Build-generated runtime attribution");

const generated = new Map();
const rows = [];
const sourceNotes = [];
for (const [key, { pkg, directory, scope }] of [...packages].sort(([a], [b]) => a.localeCompare(b, "en"))) {
  const files = readdirSync(directory).filter((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name));
  const links = [];
  if (!files.some((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name))) {
    if (key !== "@ai-sdk/provider-utils@5.0.67") {
      throw new Error(`No license text found for ${key}; review upstream before updating notices.`);
    }
    const destination = `texts/${key}-LICENSE.txt`;
    generated.set(destination, readFileSync(join(output, "upstream/provider-utils-5.0.67-LICENSE.txt"), "utf8"));
    links.push(`[LICENSE](${destination})`);
    sourceNotes.push(
      "- `@ai-sdk/provider-utils@5.0.67` omits a LICENSE file from its npm package. Its notice was retrieved from the [matching upstream tag](https://github.com/vercel/ai/blob/%40ai-sdk%2Fprovider-utils%405.0.67/LICENSE) and preserved in `upstream/`. Do not substitute its README for a license.",
    );
  }
  for (const file of files.sort()) {
    const destination = `texts/${key}-${file}.txt`;
    const text = readFileSync(join(directory, file), "utf8")
      .replaceAll("\r\n", "\n")
      .replace(/[\t ]+$/gm, "");
    if (!text.trim()) throw new Error(`Empty license/notice for ${key}`);
    generated.set(destination, text);
    links.push(`[${file}](${destination})`);
  }
  if (typeof pkg.license !== "string") throw new Error(`Review license metadata for ${key}`);
  rows.push(`| \`${key}\` | ${pkg.license} | ${scope} | ${links.join(", ")} |`);
}
generated.set(
  "NOTICE.md",
  [
    "# Third-Party Notices",
    "",
    "Generated by `tooling/update-third-party-licenses.mjs` from the installed workspace production dependency graph. Use `pnpm install --frozen-lockfile` first. Uninstalled optional platform packages are excluded; installed peer dependencies are included. Build-time stylesheet sources, adapted UI source, and build-generated runtime attribution are included separately. This is a conservative attribution inventory, not a precise bundle SBOM, a vulnerability scan, or legal clearance; a listed dependency may be tree-shaken or used only by another dependency.",
    "",
    `This snapshot includes **${packages.size} package/version pairs**. Third-party material retains its own terms, not the project's MIT license. Preserve the license and copyright texts when redistributing source or built assets. The web build does not copy these notices automatically; include the applicable license texts and notices when distributing built assets.`,
    "",
    "## Maintenance",
    "",
    "From the repository root, run `node tooling/update-third-party-licenses.mjs` to regenerate, or append `--check` to verify without writing. Review newly introduced licenses and copied source/assets manually. The generator stops when a package has no license text; do not treat a README or package metadata alone as a license. Development tools not contributing distributed source/assets are outside this inventory.",
    "",
    "## License Notes",
    "",
    "- Several Apache-2.0 packages ship only a copyright and license reference. Their notices are preserved; the [complete Apache License 2.0](Apache-2.0.txt) is also included, retrieved from https://www.apache.org/licenses/LICENSE-2.0.txt. Generated copies normalize line endings and trailing whitespace without changing the license wording.",
    "- IBM Plex Sans and IBM Plex Mono font files retain SIL OFL-1.1 terms. Keep their font copyright and license notices; do not relicense the fonts under MIT.",
    "- Lucide's upstream LICENSE includes both ISC terms and the Feather-derived MIT notice; both are preserved.",
    "- `json-schema` declares `(AFL-2.1 OR BSD-3-Clause)`; its upstream file contains both sets of terms and is preserved.",
    "- shadcn's MIT notice is retained for stylesheet imports and UI primitives adapted from shadcn/ui. Tailwind CSS also contributes generated styles.",
    "- Vite+ core's combined license file is retained for build-generated runtime helpers, including its Rolldown notice. That combined file also lists build-tool internals; inclusion does not mean all those internals ship in the site.",
    ...sourceNotes,
    "",
    "## Inventory",
    "",
    "| Package / version | Declared license | Scope | Included texts |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n"),
);
if (!readFileSync(join(output, "Apache-2.0.txt"), "utf8").includes("END OF TERMS AND CONDITIONS")) {
  throw new Error("The complete Apache-2.0 license text is required.");
}
if (!check) rmSync(join(output, "texts"), { recursive: true, force: true });
for (const [file, text] of generated) {
  const destination = join(output, file);
  if (check) {
    if (readFileSync(destination, "utf8") !== text) throw new Error(`Stale third-party notice: ${file}`);
  } else {
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, text);
  }
}
console.log(`${check ? "Verified" : "Updated"} notices for ${packages.size} package/version pairs.`);